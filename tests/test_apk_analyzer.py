# --- container validation -------------------------------------------------


def test_non_zip_upload_is_rejected() -> None:
    with pytest.raises(ApkParsingError, match="not an Android package"):
        validate_apk_container(b"this is plain text, not an apk")


def test_corrupt_zip_is_rejected() -> None:
    with pytest.raises(ApkParsingError):
        validate_apk_container(b"PK\x03\x04" + b"\x00" * 40)


def test_zip_without_a_manifest_is_rejected() -> None:
    data = build_apk(include_manifest=False)
    with pytest.raises(ApkParsingError, match="AndroidManifest"):
        validate_apk_container(data)


def test_zip_bomb_is_rejected_before_extraction() -> None:
    """A small archive expanding to 50 MB must not be inspected."""

    with pytest.raises(ApkParsingError, match="unsafe"):
        validate_apk_container(build_zip_bomb())


def test_valid_apk_passes_validation(benign_apk: bytes) -> None:
    archive = validate_apk_container(benign_apk)
    assert "AndroidManifest.xml" in {info.filename for info in archive.infolist()}
    archive.close()


# --- manifest extraction --------------------------------------------------


def test_manifest_fields_are_extracted(malicious_apk: bytes) -> None:
    facts = inspect_apk(malicious_apk)
    assert facts.manifest_parsed
    assert facts.package == "com.quickloan.instant"
    assert facts.app_label == "QuickLoan Instant"
    assert facts.target_sdk == 22
    assert facts.version_name == "1.0"


def test_all_declared_permissions_are_captured(malicious_apk: bytes) -> None:
    facts = inspect_apk(malicious_apk)
    assert set(LOAN_APP_PERMISSIONS) <= set(facts.permissions)


def test_sha256_is_stable_for_identical_bytes(benign_apk: bytes) -> None:
    assert inspect_apk(benign_apk).sha256 == inspect_apk(benign_apk).sha256


def test_limitations_always_state_static_only(benign_apk: bytes) -> None:
    facts = inspect_apk(benign_apk)
    assert any("not installed or executed" in item for item in facts.limitations)


def test_packed_apk_reports_missing_strings_rather_than_claiming_clean() -> None:
    """An APK with no readable strings must say so, not imply it is clean."""

    facts = inspect_apk(build_apk(include_dex=False))
    assert any("packed or encrypted" in item or "No DEX" in item for item in facts.limitations)


