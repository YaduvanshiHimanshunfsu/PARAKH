def test_package_name_is_recorded_as_a_linkable_identifier(
    analyzer: ApkAnalyzer, malicious_apk: bytes
) -> None:
    """The package must be linkable to the same name seen in an SMS."""

    bundle = analyzer.analyze(malicious_apk)
    packages = {i.value for i in bundle.identifiers if i.type is IdentifierType.PACKAGE}
    assert "com.quickloan.instant" in packages


def test_icon_hash_is_recorded_and_differs_between_icons(analyzer: ApkAnalyzer) -> None:
    first = analyzer.analyze(build_apk(package="com.a.b", icon_png=build_png(seed=3)))
    second = analyzer.analyze(build_apk(package="com.a.b", icon_png=build_png(seed=90)))

    def icon(bundle) -> str | None:
        values = [i.value for i in bundle.identifiers if i.type is IdentifierType.ICON_PHASH]
        return values[0] if values else None

    assert icon(first) is not None
    assert icon(first) != icon(second)


