# --- risk aggregation -----------------------------------------------------


def test_malicious_loan_app_scores_high(analyzer: ApkAnalyzer, malicious_apk: bytes) -> None:
    bundle = analyzer.analyze(malicious_apk)
    assert bundle.risk_level is RiskLevel.HIGH
    assert bundle.risk_score >= 70


def test_benign_app_does_not_score_high(analyzer: ApkAnalyzer, benign_apk: bytes) -> None:
    bundle = analyzer.analyze(benign_apk)
    assert bundle.risk_level is not RiskLevel.HIGH


def test_bundle_matches_the_shared_contract(analyzer: ApkAnalyzer, malicious_apk: bytes) -> None:
    """An APK case must flow through the same pipeline as every other artifact."""

    bundle = analyzer.analyze(malicious_apk, filename="loan.apk")
    assert bundle.artifact_type is ArtifactType.APK
    assert 0 <= bundle.risk_score <= 100
    assert bundle.content_sha256 and len(bundle.content_sha256) == 64
    assert bundle.details["package"] == "com.quickloan.instant"
    assert bundle.details["filename"] == "loan.apk"
    assert "permissions" in bundle.details


def test_analysis_is_deterministic(analyzer: ApkAnalyzer, malicious_apk: bytes) -> None:
    first = analyzer.analyze(malicious_apk)
    second = analyzer.analyze(malicious_apk)
    assert first.risk_score == second.risk_score
    assert {f.code for f in first.findings} == {f.code for f in second.findings}


def test_analysis_needs_no_ai_provider(monkeypatch, analyzer: ApkAnalyzer, malicious_apk: bytes) -> None:
    """ADR-005: an APK verdict must survive a dead or missing API key."""

    monkeypatch.delenv("GEMINI_API_KEY", raising=False)
    bundle = analyzer.analyze(malicious_apk)
    assert bundle.risk_level is RiskLevel.HIGH
    assert bundle.findings


def test_searchable_text_includes_package_and_permissions(
    analyzer: ApkAnalyzer, malicious_apk: bytes
) -> None:
    text = analyzer.analyze(malicious_apk).content_text or ""
    assert "com.quickloan.instant" in text
    assert "android.permission.READ_SMS" in text
