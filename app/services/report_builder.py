def build_cases_csv(cases: list[CaseRecord]) -> str:
    """Bulk export of a filtered case list."""

    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(
        [
            "case_id", "artifact_type", "risk_level", "risk_score", "status",
            "source", "summary", "finding_count", "identifier_count", "created_at",
        ]
    )
    for case in cases:
        writer.writerow(
            [
                case.case_id,
                case.artifact_type,
                case.risk_level,
                case.risk_score,
                case.status,
                case.source,
                (case.summary or "").replace("\n", " ")[:300],
                len(case.findings),
                len(case.identifiers),
                case.created_at.isoformat() if case.created_at else "",
            ]
        )
    return buffer.getvalue()


def build_identifiers_csv(cases: list[CaseRecord]) -> str:
    """Every identifier across the selected cases â€” the actionable export."""

    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(["case_id", "artifact_type", "risk_level", "identifier_type", "value", "confidence"])
    for case in cases:
        for identifier in case.identifiers:
            writer.writerow(
                [
                    case.case_id,
                    case.artifact_type,
                    case.risk_level,
                    identifier.type,
                    identifier.value,
                    identifier.confidence,
                ]
            )
    return buffer.getvalue()


def as_json_bytes(payload: dict) -> bytes:
    return json.dumps(payload, indent=2, ensure_ascii=False).encode("utf-8")




