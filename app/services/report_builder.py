# Patterns masked in a redacted export. Deliberately conservative: it is better
# to over-mask a shareable copy than to leak a victim's identifiers.
_REDACTIONS: tuple[tuple[re.Pattern[str], str], ...] = (
    (re.compile(r"(?<!\d)(?:\+?91[\s-]?)?[6-9]\d{4}[\s-]?\d{5}(?!\d)"), "[PHONE REDACTED]"),
    (re.compile(r"\b[A-Za-z0-9._%+\-]{1,64}@[A-Za-z0-9.\-]{1,200}\.[A-Za-z]{2,24}\b"), "[EMAIL REDACTED]"),
    (re.compile(r"\b[A-Za-z0-9][A-Za-z0-9.\-_]{1,63}@[A-Za-z]{2,24}\b"), "[UPI REDACTED]"),
    (re.compile(r"(?<!\d)\d{9,18}(?!\d)"), "[ACCOUNT REDACTED]"),
    (re.compile(r"\b[A-Z]{4}0[A-Z0-9]{6}\b"), "[IFSC REDACTED]"),
    (re.compile(r"\b0x[a-fA-F0-9]{40}\b"), "[WALLET REDACTED]"),
)

_SEVERITY_COLOUR = {"HIGH": "#b42318", "MEDIUM": "#b54708", "LOW": "#475467"}
_RISK_COLOUR = {"HIGH": "#b42318", "MEDIUM": "#b54708", "LOW": "#067647"}


def redact(text: str) -> str:
    for pattern, replacement in _REDACTIONS:
        text = pattern.sub(replacement, text)
    return text


def _esc(value: object, *, redacted: bool = False) -> str:
    text = "" if value is None else str(value)
    if redacted:
        text = redact(text)
    return html.escape(text)


def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def build_case_json(detail: CaseDetail, *, redacted: bool = False) -> dict:
    """Structured export for machine processing or handover."""

    payload = detail.model_dump(mode="json")
    payload["exported_at"] = _now()
    payload["export_mode"] = "REDACTED" if redacted else "FULL"
    payload["disclaimer"] = (
        "Generated by PARAKH static analysis. Indicators are evidence for "
        "investigation, not proof of criminal conduct."
    )
    if redacted:
        if payload.get("content_text"):
            payload["content_text"] = redact(payload["content_text"])
        for item in payload.get("identifiers", []):
            item["value"] = redact(item["value"])
            item["raw_value"] = redact(item["raw_value"])
            if item.get("context"):
                item["context"] = redact(item["context"])
        for item in payload.get("findings", []):
            if item.get("evidence"):
                item["evidence"] = redact(item["evidence"])
    return payload


